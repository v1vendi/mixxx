// [AI-generated by Claude — start]
// 0-based position of a beat in its bar, also for beats before the anchor
// downbeat (negative indices).
int beatInBar(int beatIndex, int beatsPerBar) {
    return ((beatIndex % beatsPerBar) + beatsPerBar) % beatsPerBar;
}

int beatsPerBar() {
    return std::max(1, WaveformWidgetFactory::instance()->getDownbeatDistance());
}
// [AI-generated by Claude — end]

