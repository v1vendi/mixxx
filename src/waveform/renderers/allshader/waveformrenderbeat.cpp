WaveformRenderBeat::WaveformRenderBeat(WaveformWidgetRenderer* waveformWidget,
        ::WaveformRendererAbstract::PositionSource type)
        : ::WaveformRendererAbstract(waveformWidget),
          m_isSlipRenderer(type == ::WaveformRendererAbstract::Slip),
          m_introStartPosCO(m_waveformRenderer->getGroup(),
                  QStringLiteral("intro_start_position")) {
    initForRectangles<RGBAMaterial>(0);
    setUsePreprocess(true);
}

void WaveformRenderBeat::setup(const QDomNode& node, const SkinContext& skinContext) {
    m_color = QColor(skinContext.selectString(node, QStringLiteral("BeatColor")));
    m_color = WSkinColor::getCorrectColor(m_color).toRgb();

    const QString downBeatColorName =
            skinContext.selectString(node, QStringLiteral("DownBeatColor"));
    m_downbeatColor = downBeatColorName.isEmpty() ? Qt::red : QColor(downBeatColorName);
    m_downbeatColor = WSkinColor::getCorrectColor(m_downbeatColor).toRgb();

    // [AI-generated by Claude — start]
    // rekordbox-style grid options.
    m_rekordboxStyle = skinContext.selectString(node, QStringLiteral("BeatGridStyle"))
                               .trimmed()
                               .compare(QStringLiteral("rekordbox"), Qt::CaseInsensitive) == 0;
    if (!m_rekordboxStyle) {
        return;
    }
    auto colorOr = [&](const QString& name, const QColor& fallback) {
        const QColor color = skinContext.selectColor(node, name);
        return color.isValid() ? WSkinColor::getCorrectColor(color).toRgb() : fallback;
    };
    m_barColor = colorOr(QStringLiteral("BarColor"), QColor(255, 255, 255));
    m_beatMarkerColor = colorOr(QStringLiteral("BeatMarkerColor"), QColor(140, 140, 140));
    m_barMarkerColor = colorOr(QStringLiteral("BarMarkerColor"), QColor(224, 60, 60));
    const float size = skinContext.selectFloat(node, QStringLiteral("BeatMarkerSize"), -1.f);
    if (size > 0.f) {
        m_markerSize = size;
    }
    // [AI-generated by Claude — end]
}

// [AI-generated by Claude — start]
bool WaveformRenderBeat::hasBars() const {
    return m_firstDownBeat.has_value() &&
            WaveformWidgetFactory::instance()->getDownbeatsEnabled();
}
// [AI-generated by Claude — end]

void WaveformRenderBeat::onSetTrack() {
    if (m_pLoadedTrack) {
        disconnect(m_pLoadedTrack.get(),
                &Track::beatsUpdated,
                this,
                &WaveformRenderBeat::slotBeatsUpdated);
        disconnect(m_pLoadedTrack.get(),
                &Track::cuesUpdated,
                this,
                &WaveformRenderBeat::slotCuesUpdated);
    }

    const TrackPointer pTrack = m_waveformRenderer->getTrackInfo();
    m_pLoadedTrack = pTrack;
    slotBeatsUpdated();

    if (!pTrack) {
        return;
    }

    connect(pTrack.get(),
            &Track::beatsUpdated,
            this,
            &WaveformRenderBeat::slotBeatsUpdated);
    connect(pTrack.get(),
            &Track::cuesUpdated,
            this,
            &WaveformRenderBeat::slotCuesUpdated);
}

void WaveformRenderBeat::slotBeatsUpdated() {
    setFirstDownbeatMaybeInvalid();
}

void WaveformRenderBeat::slotCuesUpdated() {
    setFirstDownbeatMaybeInvalid();
}

void WaveformRenderBeat::setFirstDownbeatMaybeInvalid() {
    mixxx::audio::FramePos introCuePos;
    if (!m_pLoadedTrack) {
        m_pTrackBeats.reset();
    } else {
        m_pTrackBeats = m_pLoadedTrack->getBeats();
        introCuePos = mixxx::audio::FramePos::fromEngineSamplePosMaybeInvalid(
                m_introStartPosCO.get());
    }

    m_firstDownBeat = std::nullopt;
    if (m_pTrackBeats && introCuePos.isValid()) {
        auto introCueBeatPos = m_pTrackBeats->findClosestBeat(introCuePos);
        auto beatIt = m_pTrackBeats->iteratorFrom(introCueBeatPos);
        if (beatIt != m_pTrackBeats->cend()) {
            m_firstDownBeat = beatIt;
        }
    }
}

void WaveformRenderBeat::draw(QPainter* painter, QPaintEvent* event) {
    Q_UNUSED(painter);
    Q_UNUSED(event);
    DEBUG_ASSERT(false);
}

void WaveformRenderBeat::preprocess() {
    if (!preprocessInner()) {
        geometry().allocate(0);
        markDirtyGeometry();
    }
}

bool WaveformRenderBeat::preprocessInner() {
    if (!m_pTrackBeats ||
            (m_isSlipRenderer && !m_waveformRenderer->isSlipActive())) {
        return false;
    }

    const TrackPointer trackInfo = m_waveformRenderer->getTrackInfo();

    const bool isStemTrack = trackInfo && trackInfo->hasStem() &&
            trackInfo->getWaveform() && trackInfo->getWaveform()->hasStem();
    const bool splitStemTracks = isStemTrack && WaveformWidgetFactory::isCreated() &&
            WaveformWidgetFactory::instance()->isStemSplitTracks();

    const double trackSamples = m_waveformRenderer->getTrackSamples();
    if (trackSamples <= 0.0) {
        return false;
    }

#ifndef __SCENEGRAPH__
    int alpha = m_waveformRenderer->getBeatGridAlpha();
    if (alpha == 0) {
        return false;
    }
    m_color.setAlphaF(alpha / 100.0f);
    m_downbeatColor.setAlphaF(alpha / 100.0f);
#endif

    if (!m_color.alpha() && !m_downbeatColor.alpha()) {
        // Don't render the beatgrid lines is there are fully transparent
        return false;
    }

    const float devicePixelRatio = m_waveformRenderer->getDevicePixelRatio();

    auto positionType = m_isSlipRenderer ? ::WaveformRendererAbstract::Slip
                                         : ::WaveformRendererAbstract::Play;
    const double firstDisplayedPosition =
            m_waveformRenderer->getFirstDisplayedPosition(positionType);
    const double lastDisplayedPosition =
            m_waveformRenderer->getLastDisplayedPosition(positionType);

    const auto startPosition = mixxx::audio::FramePos::fromEngineSamplePos(
            firstDisplayedPosition * trackSamples);
    const auto endPosition = mixxx::audio::FramePos::fromEngineSamplePos(
            lastDisplayedPosition * trackSamples);

    if (!startPosition.isValid() || !endPosition.isValid()) {
        return false;
    }

    // [AI-generated by Claude — start]
    if (m_rekordboxStyle) {
        return preprocessRekordbox(startPosition, endPosition, positionType);
    }
    // [AI-generated by Claude — end]

    const float rendererBreadth = m_waveformRenderer->getBreadth();

    const int numVerticesPerLine = 6; // 2 triangles

    // Count the number of beats in the range to reserve space in the m_vertices vector.
    // Note that we could also use
    //   int numBearsInRange = m_pTrackBeats->numBeatsInRange(startPosition, endPosition);
    // for this, but there have been reports of that method failing with a DEBUG_ASSERT.
    int numBeatsInRange = 0;
    for (auto it = m_pTrackBeats->iteratorFrom(startPosition);
            it != m_pTrackBeats->cend() && *it <= endPosition;
            ++it) {
        numBeatsInRange++;
    }

    const int numBoxesPerBeat = (m_isSlipRenderer && splitStemTracks)
            ? mixxx::kMaxSupportedStems
            : 1;
    const int reserved = numBeatsInRange * numVerticesPerLine * numBoxesPerBeat;
    geometry().allocate(reserved);

    RGBAVertexUpdater vertexUpdater{geometry().vertexDataAs<Geometry::RGBAColoredPoint2D>()};

    float beat_r = m_color.redF(), beat_g = m_color.greenF(),
          beat_b = m_color.blueF(), beat_alpha = m_color.alphaF();
    float downbeat_r = m_downbeatColor.redF(),
          downbeat_g = m_downbeatColor.greenF(),
          downbeat_b = m_downbeatColor.blueF(),
          downbeat_alpha = m_downbeatColor.alphaF();

    std::optional<mixxx::Beats::ConstIterator> firstDownbeat = std::nullopt;
    auto* pWaveformWidgetFactory = WaveformWidgetFactory::instance();
    bool downbeatsEnabled = false;
    int downbeatDistance = pWaveformWidgetFactory->getDownbeatDistance();
    if (pWaveformWidgetFactory->getDownbeatsEnabled() && m_firstDownBeat.has_value()) {
        downbeatsEnabled = true;
        firstDownbeat = *m_firstDownBeat;
    }

    const float boxBreadth = splitStemTracks
            ? rendererBreadth / static_cast<float>(mixxx::kMaxSupportedStems)
            : rendererBreadth;

    for (auto it = m_pTrackBeats->iteratorFrom(startPosition);
            it != m_pTrackBeats->cend() && *it <= endPosition;
            ++it) {
        double beatPosition = it->toEngineSamplePos();
        double xBeatPoint =
                m_waveformRenderer->transformSamplePositionInRendererWorld(
                        beatPosition, positionType);

        xBeatPoint = qRound(xBeatPoint * devicePixelRatio) / devicePixelRatio;

        const float x1 = static_cast<float>(xBeatPoint);
        const float x2 = x1 + 1.f;

        const bool isDownbeat = downbeatsEnabled &&
                std::distance(*firstDownbeat, it) % downbeatDistance == 0;
        const QVector4D color = isDownbeat
                ? QVector4D{downbeat_r, downbeat_g, downbeat_b, downbeat_alpha}
                : QVector4D{beat_r, beat_g, beat_b, beat_alpha};

        if (m_isSlipRenderer && splitStemTracks) {
            for (int stemIdx = 0; stemIdx < mixxx::kMaxSupportedStems; ++stemIdx) {
                const float posy1 = stemIdx * boxBreadth;
                const float posy2 = posy1 + boxBreadth / 2.f;
                vertexUpdater.addRectangle({x1, posy1}, {x2, posy2}, color);
            }
        } else {
            vertexUpdater.addRectangle({x1, 0.f},
                    {x2, m_isSlipRenderer ? rendererBreadth / 2 : rendererBreadth},
                    color);
        }
    }
    markDirtyGeometry();

    DEBUG_ASSERT(reserved == vertexUpdater.index());

    markDirtyMaterial();

    return true;
}

// [AI-generated by Claude — start]
// Builds the rekordbox-style grid: a line per beat plus top and bottom tick
// triangles, with downbeats highlighted. Unlike the stock grid, the slip
// renderer does not split the lines per stem on split-stem tracks: the
// lines span the whole slip half.
bool WaveformRenderBeat::preprocessRekordbox(mixxx::audio::FramePos startPosition,
        mixxx::audio::FramePos endPosition,
        ::WaveformRendererAbstract::PositionSource positionType) {
    const float devicePixelRatio = m_waveformRenderer->getDevicePixelRatio();
    const float breadth = m_isSlipRenderer
            ? m_waveformRenderer->getBreadth() / 2
            : m_waveformRenderer->getBreadth();
    // m_color carries the user's beat grid opacity
    const float alpha = m_color.alphaF();

    auto rgba = [alpha](const QColor& color) {
        return QVector4D(color.redF(), color.greenF(), color.blueF(), color.alphaF() * alpha);
    };
    const QVector4D beatLine(m_color.redF(), m_color.greenF(), m_color.blueF(), alpha);
    const QVector4D barLine = rgba(m_barColor);
    const QVector4D beatMarker = rgba(m_beatMarkerColor);
    const QVector4D barMarker = rgba(m_barMarkerColor);

    int numBeatsInRange = 0;
    for (auto it = m_pTrackBeats->iteratorFrom(startPosition);
            it != m_pTrackBeats->cend() && *it <= endPosition;
            ++it) {
        numBeatsInRange++;
    }
    // per beat: one line (2 triangles) + top and bottom tick (1 triangle each)
    const int numVerticesPerBeat = 6 + 3 + 3;
    const int reserved = numBeatsInRange * numVerticesPerBeat;
    geometry().allocate(reserved);

    RGBAVertexUpdater vertexUpdater{geometry().vertexDataAs<Geometry::RGBAColoredPoint2D>()};

    // Iterator distance walks the marker list, so compute the position of the
    // first visible beat relative to the anchor downbeat once and count from
    // there.
    const bool bars = hasBars();
    const int barLength = beatsPerBar();
    auto it = m_pTrackBeats->iteratorFrom(startPosition);
    int beatIndex = bars && numBeatsInRange > 0 ? it - *m_firstDownBeat : 0;
    for (; it != m_pTrackBeats->cend() && *it <= endPosition; ++it, ++beatIndex) {
        const bool isDownbeat = bars && beatInBar(beatIndex, barLength) == 0;

        double xBeatPoint = m_waveformRenderer->transformSamplePositionInRendererWorld(
                it->toEngineSamplePos(), positionType);
        xBeatPoint = qRound(xBeatPoint * devicePixelRatio) / devicePixelRatio;
        const float x = static_cast<float>(xBeatPoint);

        vertexUpdater.addRectangle({x, 0.f},
                {x + 1.f, breadth},
                isDownbeat ? barLine : beatLine);

        const float half = isDownbeat ? m_markerSize : m_markerSize * 0.7f;
        const float depth = half * 1.2f;
        const float cx = x + 0.5f;
        const QVector4D& markerColor = isDownbeat ? barMarker : beatMarker;
        // top tick points down, bottom tick points up
        vertexUpdater.addTriangle({cx - half, 0.f}, {cx + half, 0.f}, {cx, depth}, markerColor);
        vertexUpdater.addTriangle({cx - half, breadth},
                {cx + half, breadth},
                {cx, breadth - depth},
                markerColor);
    }
    markDirtyGeometry();

    DEBUG_ASSERT(reserved == vertexUpdater.index());

    return true;
}
